// Converts the wordmark to outlines, once, and writes design/wordmark.mjs.
//
// Run it only to change the wordmark's text or typeface. Nothing else in the
// repository needs the font file: the outlines it writes are committed, so
// every other script and every build works from the module and never from a
// font that has to be installed, downloaded, or licensed at build time.
//
//   node design/build-wordmark.mjs --font ~/Downloads/JetBrainsMono-Bold.ttf
//
// The module it writes is formatted the way Prettier would format it, so
// regenerating it never shows up as a diff of line breaks.
//
// The typeface is JetBrains Mono Bold, under the SIL Open Font License 1.1
// (https://github.com/JetBrains/JetBrainsMono, OFL.txt in that repository).
// The OFL permits using the font to make artwork and distributing the result;
// what it restricts is selling or renaming the font software itself, which
// nothing here does. design/README.md records the choice and why it is that
// typeface, and the generated module repeats the attribution so a reader of the
// path data knows what it came from.

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { join } from "node:path";

import { pathBounds, readFont, textToPath } from "./ttf-outlines.mjs";

/** The em the outlines are expressed in. Round, so the numbers stay readable. */
const EM = 100;

const TEXT = "flow-as-code";
const FACE = "JetBrains Mono Bold";
const LICENSE = "SIL Open Font License 1.1";
const SOURCE = "https://github.com/JetBrains/JetBrainsMono";

function main() {
  const argv = process.argv.slice(2);
  const at = argv.indexOf("--font");
  if (at === -1 || argv[at + 1] === undefined) {
    console.error(
      "usage: node design/build-wordmark.mjs --font <path to a .ttf>\n" +
        `The wordmark is ${FACE} (${LICENSE}, ${SOURCE}).`,
    );
    process.exit(1);
  }

  const font = readFont(readFileSync(argv[at + 1]));
  const { d, width } = textToPath(font, TEXT, { size: EM, x: 0, y: 0 });
  const box = pathBounds(d);
  const round = (value) => Number(value.toFixed(2));

  const out = join(fileURLToPath(new URL(".", import.meta.url)), "wordmark.mjs");
  writeFileSync(
    out,
    `/*
 * Copyright 2026 The flow-as-code Authors
 * SPDX-License-Identifier: Apache-2.0
 */

// GENERATED by design/build-wordmark.mjs. Do not edit by hand.
//
// "${TEXT}" set in ${FACE} and converted to outlines, so the wordmark is the
// same shape on every machine. An SVG <text> element would render in whatever
// font the viewer happens to have, and a logo that changes shape per viewer is
// not a logo.
//
// ${FACE} is licensed under the ${LICENSE}
// (${SOURCE}). These are outlines
// produced with it, not the font software, and no glyph outside the twelve
// characters of the wordmark is here.
//
// The path is laid out on the baseline y = 0 starting at x = 0, with the em set
// to ${String(EM)} units. Scale it, do not re-space it: the advances below are the
// typeface's own and the face is monospaced.

/** The em these coordinates are expressed in. */
export const WORDMARK_EM = ${String(EM)};

/** The text the outlines spell, for an accessible name and for a check. */
export const WORDMARK_TEXT = ${JSON.stringify(TEXT)};

/** The typeface and its license, repeated here for whoever reads the data. */
export const WORDMARK_FACE =
  ${JSON.stringify(`${FACE}, ${LICENSE}, ${SOURCE}`)};

/** Total advance of the string, in the same units as the path. */
export const WORDMARK_ADVANCE = ${String(round(width))};

/**
 * The ink, measured off the curves rather than off the control points: \`top\`
 * is the tallest ascender above the baseline and \`bottom\` is the overshoot of
 * the round letters below it. The wordmark has no descender.
 */
export const WORDMARK_INK = {
  left: ${String(round(box.minX))},
  right: ${String(round(box.maxX))},
  top: ${String(round(-box.minY))},
  bottom: ${String(round(box.maxY))},
};

/** Every glyph of the wordmark, as one path, filled with the nonzero rule. */
export const WORDMARK_PATH =
  "${d}";
`,
  );
  console.log(
    `build-wordmark: wrote ${out}\n` +
      `  ${TEXT} in ${FACE}: advance ${String(round(width))}, ` +
      `ink ${String(round(-box.minY))} above and ${String(round(box.maxY))} below the baseline.`,
  );
}

main();
