describe("@keep comments survive regeneration", () => {
  it("re-attaches @keep comments to the matching block and the export", () => {
    const doc = demoDoc();
    const base = codegen(doc);
    const previous = base
      .replace(
        "    new CheckHoursOfOperation({",
        "    // Business hours drive everything below. @keep\n    // scratch note, not kept\n    new CheckHoursOfOperation({",
      )
      .replace(
        "export function appointmentLine",
        "// Reviewed by on-call. @keep\nexport function appointmentLine",
      );
    const regen = codegen(doc, { previous });
    expect(regen).toContain(
      "    // Business hours drive everything below. @keep\n    new CheckHoursOfOperation({",
    );
    expect(regen).toContain("// Reviewed by on-call. @keep\nexport function appointmentLine");
    expect(regen).not.toContain("scratch note");
  });

  it("is idempotent: regenerating from its own output changes nothing", () => {
    const doc = demoDoc();
    const base = codegen(doc);
    expect(codegen(doc, { previous: base })).toBe(base);
    const withKeep = codegen(doc, {
      previous: base.replace(
        '    new DisconnectParticipant({ id: "hang-up" }),',
        '    // Terminal on purpose. @keep\n    new DisconnectParticipant({ id: "hang-up" }),',
      ),
    });
    expect(codegen(doc, { previous: withKeep })).toBe(withKeep);
  });

  it("drops a @keep comment whose block id no longer exists", () => {
    const doc = demoDoc();
    const base = codegen(doc);
    const previous = base.replace(
      '    new MessageParticipant({\n      id: "welcome",',
      '    // Stale note. @keep\n    new MessageParticipant({\n      id: "gone-now",',
    );
    const regen = codegen(doc, { previous });
    expect(regen).not.toContain("Stale note");
  });
});
